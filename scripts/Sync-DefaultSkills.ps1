# Regenerate the standing default output style in Codex config.toml from the
# caveman and i-have-adhd SKILL.md files. Windows port of
# ~/.codex/bin/sync-default-skills.sh.
[CmdletBinding()]
param(
    [string]$ConfigPath = (Join-Path $HOME '.codex/config.toml'),
    [string]$SkillsDir = (Join-Path $HOME '.agents/skills'),
    [switch]$DryRun
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$begin = '# BEGIN default-skills (generated by scripts/Sync-DefaultSkills.ps1)'
$end = '# END default-skills (generated by scripts/Sync-DefaultSkills.ps1)'

function Get-SkillBody {
    param([string]$Path)
    if (-not (Test-Path $Path)) { throw "missing skill file: $Path" }
    $text = Get-Content -Raw -LiteralPath $Path
    if ($text.StartsWith("---`n") -or $text.StartsWith("---`r`n")) {
        $match = [regex]::Match($text, '(?s)^---\r?\n.*?\r?\n---\r?\n')
        if ($match.Success) { $text = $text.Substring($match.Length) }
    }
    return $text.Trim()
}

$caveman = Get-SkillBody -Path (Join-Path $SkillsDir 'caveman/SKILL.md')
$adhd = Get-SkillBody -Path (Join-Path $SkillsDir 'i-have-adhd/SKILL.md')

$block = @"
$begin
# Standing default output style for every Codex session, in every repo. This
# block is generated: edit the SKILL.md files, then re-run
# scripts/Sync-DefaultSkills.ps1
developer_instructions = '''
These skills are ACTIVE by default in every session, every repo. Apply them
without being asked and without announcing them.

Caveman level is ULTRA. Where the caveman skill below calls its own default
"full", read "ultra" instead. Turn either style off with "stop caveman",
"stop adhd mode" or "normal mode".

===== SKILL: caveman =====

$caveman

===== SKILL: i-have-adhd =====

$adhd
'''
$end
"@

$source = Get-Content -Raw -LiteralPath $ConfigPath
$source = [regex]::Replace($source, '(?s)' + [regex]::Escape($begin) + '.*?' + [regex]::Escape($end) + '\r?\n?', '')
$source = [regex]::Replace($source, '(?s)# BEGIN default-skills.*?# END default-skills\r?\n?', '')
$source = [regex]::Replace($source, '(?sm)^developer_instructions = """.*?"""\r?\n', '')

$anchor = '# network_access = "enabled"'
if ($source.Contains($anchor)) {
    $output = $source.Replace($anchor, $anchor + "`r`n`r`n" + $block)
}
else {
    $output = $source.TrimEnd() + "`r`n`r`n" + $block + "`r`n"
}

if ($DryRun) {
    Write-Host $output.Substring(0, [Math]::Min(400, $output.Length))
    return
}

$stamp = Get-Date -Format 'yyyyMMddHHmmss'
Copy-Item -LiteralPath $ConfigPath -Destination "$ConfigPath.bak-$stamp" -Force
[IO.File]::WriteAllText($ConfigPath, $output, (New-Object Text.UTF8Encoding($false)))
Write-Ok "default skills synced into $ConfigPath"
